    private void button1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button1ActionPerformed
        
        
        try {

        String carnet = textField2.getText();
        String nombre = textField1.getText();
        int edad = Integer.parseInt(textField3.getText());
        String carrera = textField4.getText();

        Estudiante estudiante = new Estudiante(carnet,nombre,edad,carrera);

        lista.guardar(estudiante);
        actualizarTabla();


    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,"Ingrese un numero entero");
    }
        
    }//GEN-LAST:event_button1ActionPerformed

    private void button2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button2ActionPerformed
        String carnet = textField2.getText();
        Estudiante estudiante = lista.buscar(carnet);
        if (estudiante != null) {
            textField1.setText(estudiante.getNombre());
            textField3.setText(String.valueOf(estudiante.getEdad()));
            textField4.setText(estudiante.getCarrera());

        } else {

        JOptionPane.showMessageDialog(this, "Estudiante no encontrado");
        }
    }//GEN-LAST:event_button2ActionPerformed

    private void button3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button3ActionPerformed
        String carnet = textField2.getText();
        String nombre = textField1.getText();
        int edad = Integer.parseInt(textField3.getText());
        String carrera = textField4.getText();

        boolean resultado = lista.modificar(carnet, nombre, edad, carrera);

        if (resultado) {
            actualizarTabla();
            JOptionPane.showMessageDialog(this, "Estudiante modificado");
        } else {
            JOptionPane.showMessageDialog(this, "Estudiante no encontrado");
        }
    }//GEN-LAST:event_button3ActionPerformed

    private void button4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button4ActionPerformed
        String carnet = textField2.getText();
        boolean resultado = lista.eliminar(carnet);
        if (resultado) {
            actualizarTabla();
            JOptionPane.showMessageDialog(this, "Estudiante eliminado");
          } else {
        JOptionPane.showMessageDialog(this, "Estudiante no encontrado");
        }
    }//GEN-LAST:event_button4ActionPerformed

